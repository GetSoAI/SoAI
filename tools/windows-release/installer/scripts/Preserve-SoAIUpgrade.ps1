[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$InstallRoot,
    [string]$BackupRoot,
    [string]$CandidateManifestPath,
    [string]$ControlLauncherPath = '',
    [string]$StageRoot = '',
    [Parameter(Mandatory=$true)][ValidateSet('Backup','Prepare','Restore','Cleanup','Inventory')][string]$Mode
)

$ErrorActionPreference = 'Stop'
trap { if ($env:SOAI_INSTALLER_FAILURE_PATH) { try { [IO.File]::WriteAllText($env:SOAI_INSTALLER_FAILURE_PATH, (($_.Exception.Message -replace '\s+', ' ').Trim()), [Text.Encoding]::Unicode) } catch { } }; break }

function Resolve-FullPath {
    param([Parameter(Mandatory=$true)][string]$Path)
    $executionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Path)
}

function ConvertTo-ExtendedPath {
    param([Parameter(Mandatory=$true)][string]$Path)
    $resolved = Resolve-FullPath $Path
    if ($resolved.StartsWith('\\?\', [StringComparison]::Ordinal)) {
        return $resolved
    }
    if ($resolved.StartsWith('\\', [StringComparison]::Ordinal)) {
        return '\\?\UNC\' + $resolved.Substring(2)
    }
    return '\\?\' + $resolved
}

function Resolve-ChildPath {
    param(
        [Parameter(Mandatory=$true)][string]$Root,
        [Parameter(Mandatory=$true)][string]$Child
    )
    $resolvedRoot = Resolve-FullPath $Root
    $resolvedChild = Resolve-FullPath (Join-Path $resolvedRoot $Child)
    $prefix = $resolvedRoot.TrimEnd('\') + '\'
    if (!$resolvedChild.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "Refusing to use a path outside its transaction root: $resolvedChild"
    }
    return $resolvedChild
}

function Assert-SafeRoots {
    $resolvedInstallRoot = Resolve-FullPath $InstallRoot
    $resolvedBackupRoot = Resolve-FullPath $BackupRoot
    $driveRoot = [System.IO.Path]::GetPathRoot($resolvedInstallRoot).TrimEnd('\')
    if ([string]::Equals($resolvedInstallRoot.TrimEnd('\'), $driveRoot, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw 'The SoAI install root cannot be a drive root.'
    }
    if ([string]::Equals($resolvedInstallRoot.TrimEnd('\'), $resolvedBackupRoot.TrimEnd('\'), [System.StringComparison]::OrdinalIgnoreCase)) {
        throw 'The SoAI upgrade backup must be separate from the install root.'
    }
    if (($resolvedBackupRoot.TrimEnd('\') + '\').StartsWith($resolvedInstallRoot.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase) -or
        ($resolvedInstallRoot.TrimEnd('\') + '\').StartsWith($resolvedBackupRoot.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase)) {
        throw 'The installation and its retained backup must not contain each other.'
    }
    if (!(Split-Path -Leaf $resolvedBackupRoot).Contains('-SoAI-Upgrade-')) {
        throw 'The SoAI upgrade backup directory name is invalid.'
    }
    return @($resolvedInstallRoot, $resolvedBackupRoot)
}

function Get-ManifestRollbackRoots {
    param([Parameter(Mandatory=$true)][string]$ManifestPath)
    # Rollback verification fingerprints each release-owned tree whole, including
    # generated bytecode, so the backup preserves those trees rather than listed files.
    Get-Content -LiteralPath $ManifestPath | ForEach-Object {
        $components = @($_.Trim() -split '\\')
        if ($components[0].Length -gt 0) {
            $depth = if ($components[0] -eq 'data') { 2 } else { 1 }
            ($components | Select-Object -First $depth) -join '\'
        }
    }
}

function Copy-RollbackPath {
    param(
        [Parameter(Mandatory=$true)][string]$SourceRoot,
        [Parameter(Mandatory=$true)][string]$DestinationRoot,
        [Parameter(Mandatory=$true)][string]$RelativePath
    )
    $source = ConvertTo-ExtendedPath (Resolve-ChildPath -Root $SourceRoot -Child $RelativePath)
    if (!(Test-Path -LiteralPath $source)) {
        return
    }
    $item = Get-Item -LiteralPath $source -Force
    if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw 'Installer preservation encountered a reparse point; original state was not replaced.'
    }
    $destination = ConvertTo-ExtendedPath (Resolve-ChildPath -Root $DestinationRoot -Child $RelativePath)
    if ($item.PSIsContainer) {
        New-Item -ItemType Directory -Force -Path $destination | Out-Null
        Copy-InstallDiscretionaryAcl -Source $source -Destination $destination
        foreach ($child in Get-ChildItem -LiteralPath $source -Force) {
            Copy-RollbackPath -SourceRoot $SourceRoot -DestinationRoot $DestinationRoot -RelativePath (Join-Path $RelativePath $child.Name)
        }
    }
    else {
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $destination) | Out-Null
        Copy-Item -LiteralPath $source -Destination $destination -Force
        Copy-InstallDiscretionaryAcl -Source $source -Destination $destination
    }
}

function Copy-InstallDiscretionaryAcl {
    param([Parameter(Mandatory=$true)][string]$Source, [Parameter(Mandatory=$true)][string]$Destination)
    $sections = [Security.AccessControl.AccessControlSections]::Access
    $sourceSecurity = Get-Acl -LiteralPath $Source
    $destinationSecurity = Get-Acl -LiteralPath $Destination
    $destinationSecurity.SetSecurityDescriptorSddlForm($sourceSecurity.GetSecurityDescriptorSddlForm($sections), $sections)
    Set-Acl -LiteralPath $Destination -AclObject $destinationSecurity
}

function Invoke-UpgradeRecoveryCommand {
    param([string]$Root, [string]$Python, [string]$Code, [string[]]$Arguments, [string]$Phase)
    $reference = [Guid]::NewGuid().ToString('N')
    $diagnosticParent = [IO.Path]::GetDirectoryName($resolvedBackupRoot)
    $diagnosticRoot = Join-Path $diagnosticParent ('SoAI-Recovery-' + $reference)
    New-Item -ItemType Directory -Path $diagnosticRoot | Out-Null
    $stdout = Join-Path $diagnosticRoot 'stdout.txt'
    $stderr = Join-Path $diagnosticRoot 'stderr.txt'
    $started = [DateTime]::UtcNow
    $elapsed = [Diagnostics.Stopwatch]::StartNew()
    $interpreterHash = $null
    $nativeExit = $null
    $timedOut = $false
    $process = $null
    $timeoutSeconds = 18000
    $commandArguments = '-B -P -S -c "{0}"' -f $Code
    foreach ($argument in $Arguments) { $commandArguments += ' "' + $argument + '"' }
    try {
        $interpreterHash = (Get-FileHash -LiteralPath (ConvertTo-ExtendedPath $Python) -Algorithm SHA256).Hash.ToLowerInvariant()
        $process = Start-Process -FilePath $Python -ArgumentList $commandArguments -WorkingDirectory $Root -PassThru -WindowStyle Hidden -RedirectStandardOutput $stdout -RedirectStandardError $stderr
        $null = $process.Handle
        if (!$process.WaitForExit($timeoutSeconds * 1000)) {
            $timedOut = $true
            $process.Kill()
            if (!$process.WaitForExit(30000)) { throw ('Installer recovery could not verify process exit. Diagnostic reference: ' + $reference) }
        }
        $nativeExit = $process.ExitCode
        if ($timedOut -or $nativeExit -ne 0) {
            throw ('Installer ' + $Phase + ' failed; preserve the retained originals. Diagnostic reference: ' + $reference)
        }
    }
    finally {
        if ($process) { $process.Dispose() }
        $elapsed.Stop()
        [ordered]@{
            reference = $reference
            phase = $Phase
            executable = $Python
            interpreter_sha256 = $interpreterHash
            working_directory = $Root
            arguments = $Arguments
            started_utc = $started.ToString('o')
            finished_utc = [DateTime]::UtcNow.ToString('o')
            timeout_seconds = $timeoutSeconds
            elapsed_seconds = $elapsed.Elapsed.TotalSeconds
            native_exit = $nativeExit
            timed_out = $timedOut
            stdout = $stdout
            stderr = $stderr
        } | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath (Join-Path $diagnosticRoot 'command.json') -Encoding UTF8
    }
}

function Restore-PluginUpgradeState {
    param([Parameter(Mandatory=$true)][string]$Root, [ValidateSet('restore','cleanup')][string]$Phase)
    $updateOwned = Test-Path -LiteralPath (Join-Path $Root 'data\locks\soai.update.lock.d')
    $transactions = @(Get-ChildItem -LiteralPath $Root -Force | Where-Object { $_.Name.StartsWith('.soai_update_transaction_', [StringComparison]::Ordinal) -or $_.Name.StartsWith('.soai_update_cleanup_', [StringComparison]::Ordinal) })
    if ($transactions.Count -eq 0) {
        if ($Phase -eq 'restore') { throw 'Native restoration has no matching protected transaction. Retain the original backup and repair its transaction authority before retrying.' }
        return
    }
    if ($transactions.Count -ne 1 -or !$transactions[0].PSIsContainer -or ($transactions[0].Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        throw 'Installer recovery has conflicting transaction evidence; preserve the originals.'
    }
    $transaction = $transactions[0].FullName
    if ($Phase -eq 'restore' -and $transactions[0].Name.StartsWith('.soai_update_cleanup_', [StringComparison]::Ordinal)) { throw 'Native application restoration is unavailable from terminal cleanup storage. Retain the native backup and verify application state before retrying.' }
    $armed = Test-Path -LiteralPath (Join-Path $transaction 'rollback_required') -PathType Leaf
    $python = if ($Phase -eq 'cleanup') { Join-Path $Root 'python\python.exe' } elseif ($armed) { Join-Path $transaction 'recovery_runtime\python.exe' } else { Join-Path $Root 'soai_main_venv\Scripts\python.exe' }
    if (!(Test-Path -LiteralPath $python -PathType Leaf)) {
        throw 'The protected installer recovery interpreter is missing; preserve the originals.'
    }
    $previousPythonPath = $env:PYTHONPATH
    $previousBytecode = $env:PYTHONDONTWRITEBYTECODE
    try {
        $env:PYTHONPATH = Join-Path $StageRoot 'backend'
        $env:PYTHONDONTWRITEBYTECODE = '1'
        $recoveryCode = @'
import sys
from app.updater.software_update.recovery_bootstrap import resolve_update_recovery_package_paths
sys.path.extend(resolve_update_recovery_package_paths(sys.argv[1]))
from app.updater.installation_plugin_upgrade import finish_installation_plugin_upgrade
from app.updater.software_update.install_transaction_state import marker_path, paths_from_transaction_directory
from app.updater.software_update.update_lock import resolve_software_update_lock_dir
from app.updater.windows_installer_preparation import verify_windows_installer_original_backup
from core.errors.exceptions import StateError
import os
paths = paths_from_transaction_directory(sys.argv[1], sys.argv[3])
finish_installation_plugin_upgrade(sys.argv[1], edition='soai-core', success=False, retained_installation_root=sys.argv[2], cleanup_after_recovery=False)
if os.path.lexists(resolve_software_update_lock_dir(sys.argv[1])):
    raise StateError('Protected restoration remains delegated to the verified external updater; local completion is pending.')
if os.path.isfile(marker_path(paths.transaction_path,'rollback_required')) and not os.path.isfile(marker_path(paths.transaction_path,'rollback_complete')):
    raise StateError('Protected restoration remains delegated to the verified external updater; local completion is pending.')
verify_windows_installer_original_backup(paths, sys.argv[2])
'@
        $cleanupCode = @'
import os
import sys
from app.updater.software_update.recovery_bootstrap import resolve_update_recovery_package_paths
sys.path.extend(resolve_update_recovery_package_paths(sys.argv[1]))
from app.updater.software_update.install_transaction_recovery import recover_interrupted_update_transactions
from core.logging.trace import get_logger
recovered = recover_interrupted_update_transactions(sys.argv[1], get_logger('SoAI.installer.recovery'), allow_pending_activation=True, allow_restoration=False)
if recovered and any(name.startswith(('.soai_update_transaction_', '.soai_update_cleanup_')) for name in os.listdir(sys.argv[1])):
    raise RuntimeError('Installer recovery cleanup did not reach its transaction postcondition.')
raise SystemExit(0 if recovered else 1)
'@
        if ($Phase -eq 'cleanup') {
            if ($updateOwned) { throw 'Update cleanup remains owned by the verified external updater; local completion is pending.' }
            $python = Join-Path $Root 'python\python.exe'
            if (!(Test-Path -LiteralPath $python -PathType Leaf)) { throw 'The restored standalone interpreter is missing; cleanup requires repair.' }
        }
        $code = if ($Phase -eq 'restore') { $recoveryCode } else { $cleanupCode }
        Invoke-UpgradeRecoveryCommand -Root $Root -Python $python -Code $code -Arguments @($Root, $resolvedBackupRoot, $transaction) -Phase $Phase
    }
    finally {
        $env:PYTHONPATH = $previousPythonPath
        $env:PYTHONDONTWRITEBYTECODE = $previousBytecode
    }
}

function Remove-RollbackPath {
    param(
        [Parameter(Mandatory=$true)][string]$Root,
        [Parameter(Mandatory=$true)][string]$RelativePath
    )
    $target = ConvertTo-ExtendedPath (Resolve-ChildPath -Root $Root -Child $RelativePath)
    if (Test-Path -LiteralPath $target) {
        Remove-Item -LiteralPath $target -Recurse -Force
    }
}

function Restore-Launcher {
    param(
        [Parameter(Mandatory=$true)][string]$SourceRoot,
        [Parameter(Mandatory=$true)][string]$DestinationRoot
    )
    $source = Resolve-ChildPath -Root $SourceRoot -Child 'soai.exe'
    if (!(Test-Path -LiteralPath $source -PathType Leaf)) {
        return
    }
    $destination = Resolve-ChildPath -Root $DestinationRoot -Child 'soai.exe'
    $candidate = Resolve-ChildPath -Root $DestinationRoot -Child 'installer-support\.soai-launcher.pending'
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $candidate) | Out-Null
    if (Test-Path -LiteralPath $candidate) {
        Remove-Item -LiteralPath $candidate -Force
    }
    Add-Type -TypeDefinition @'
using System.Runtime.InteropServices;
public static class SoAIInstallerLauncherFile {
    [DllImport("kernel32.dll", CharSet=CharSet.Unicode, SetLastError=true)]
    public static extern bool MoveFileEx(string source, string destination, int flags);
}
'@
    $original = [IO.File]::OpenRead($source)
    try {
        $staged = [IO.File]::Open($candidate, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
        try {
            $original.CopyTo($staged)
            $staged.Flush($true)
        }
        finally { $staged.Dispose() }
    }
    finally { $original.Dispose() }
    Copy-InstallDiscretionaryAcl -Source $source -Destination $candidate
    if (![SoAIInstallerLauncherFile]::MoveFileEx($candidate, $destination, 9)) {
        throw [ComponentModel.Win32Exception]::new(
            [Runtime.InteropServices.Marshal]::GetLastWin32Error(),
            'The retained SoAI launcher could not be restored atomically.'
        )
    }
}

function Test-TrailingEndOfFileByte {
    param([Parameter(Mandatory=$true)][string]$Path)
    $stream = [IO.File]::Open($Path, [IO.FileMode]::Open, [IO.FileAccess]::Read, [IO.FileShare]::Read)
    try {
        if ($stream.Length -eq 0) {
            return $false
        }
        [void]$stream.Seek(-1, [IO.SeekOrigin]::End)
        return $stream.ReadByte() -eq 0x1A
    }
    finally {
        $stream.Dispose()
    }
}

function Repair-TrailingEndOfFileBytes {
    param(
        [Parameter(Mandatory=$true)][string]$Root,
        [Parameter(Mandatory=$true)][string]$StageRoot
    )
    $nativeRoot = (ConvertTo-ExtendedPath $Root).TrimEnd('\')
    $nativeStage = (ConvertTo-ExtendedPath $StageRoot).TrimEnd('\')
    foreach ($stagedEntry in [IO.Directory]::GetFileSystemEntries($nativeStage)) {
        $name = [IO.Path]::GetFileName($stagedEntry)
        if ($name -eq 'data') {
            continue
        }
        $installedEntry = $nativeRoot + '\' + $name
        $installedFiles = if ([IO.Directory]::Exists($installedEntry)) {
            [IO.Directory]::EnumerateFiles($installedEntry, '*', [IO.SearchOption]::AllDirectories)
        }
        elseif ([IO.File]::Exists($installedEntry)) {
            @($installedEntry)
        }
        else {
            @()
        }
        foreach ($installedFile in $installedFiles) {
            if (([IO.File]::GetAttributes($installedFile) -band [IO.FileAttributes]::ReparsePoint) -ne 0 -or
                !(Test-TrailingEndOfFileByte -Path $installedFile)) {
                continue
            }
            $stagedFile = $nativeStage + $installedFile.Substring($nativeRoot.Length)
            if ([IO.File]::Exists($stagedFile) -and !(Test-TrailingEndOfFileByte -Path $stagedFile)) {
                [IO.File]::Copy($stagedFile, $installedFile, $true)
            }
        }
    }
}

$runtimeRollbackDirectories = @(
    'plugins',
    'data\config',
    'python',
    'python-3.13',
    'runtime',
    'soai_main_venv',
    'soai_python',
    'webview2',
    'data\state\java',
    'data\state\playwright-browsers',
    'data\state\tika',
    'data\state\tiktoken-cache',
    'installer-support\logs'
)
$runtimeRollbackFiles = @(
    'soai.exe.config',
    'data\state\windows-install.json',
    'msvcp140.dll',
    'msvcp140_1.dll',
    'msvcp140_2.dll',
    'msvcp140_atomic_wait.dll',
    'msvcp140_codecvt_ids.dll',
    'vcruntime140.dll',
    'vcruntime140_1.dll'
)


$installationMetadataPaths = @(
    '.soai-install-root',
    '.soai_install_manifest.json',
    'Uninstall.exe',
    'installer-support\installed-files.txt'
)
$runtimeRollbackPaths = @($runtimeRollbackDirectories) + @($runtimeRollbackFiles)
if ($Mode -eq 'Inventory') {
    $manifestPath = Join-Path $InstallRoot 'installer-support\installed-files.txt'
    if (!(Test-Path -LiteralPath $manifestPath -PathType Leaf)) {
        throw 'The existing SoAI installation manifest is missing.'
    }
    $manifestFiles = @(Get-Content -LiteralPath $manifestPath | ForEach-Object { $_.Trim() } | Where-Object { $_.Length -gt 0 })
    Repair-TrailingEndOfFileBytes -Root $InstallRoot -StageRoot (Split-Path -Parent $PSScriptRoot)
    [ordered]@{
        directories = @($runtimeRollbackDirectories | ForEach-Object { $_.Replace('\', '/') })
        files = @((@($runtimeRollbackFiles) + @($installationMetadataPaths) + $manifestFiles) | ForEach-Object { $_.Replace('\', '/') } | Sort-Object -Unique)
    } | ConvertTo-Json -Compress
    exit 0
}
if ([string]::IsNullOrWhiteSpace($BackupRoot)) {
    throw 'The SoAI upgrade transaction requires a backup root.'
}
$roots = Assert-SafeRoots
$resolvedInstallRoot = $roots[0]
$resolvedBackupRoot = $roots[1]
if ([string]::IsNullOrWhiteSpace($ControlLauncherPath) -or [string]::IsNullOrWhiteSpace($env:SOAI_INSTALL_LOCK_HELD_PATH)) {
    throw 'Native preservation requires the verified installer ownership and current control launcher. Run the owning installer recovery entrypoint.'
}
[Reflection.Assembly]::Load([IO.File]::ReadAllBytes((ConvertTo-ExtendedPath $ControlLauncherPath))) | Out-Null
$coordinator = [SoAILauncher.NativeFilesystemHandles]::OpenInstallerBootstrapGate($resolvedInstallRoot)
$sourceAncestors = @()
$backupAncestors = @()
try {
$sourceAncestors = [SoAILauncher.NativeFilesystemHandles]::RetainDirectoryAncestors($resolvedInstallRoot)
$backupAncestors = [SoAILauncher.NativeFilesystemHandles]::RetainDirectoryAncestors([IO.Path]::GetDirectoryName($resolvedBackupRoot))
if ($Mode -in @('Prepare', 'Restore')) {
    if ([string]::IsNullOrWhiteSpace($StageRoot)) { throw 'Native transaction verification requires the current installer candidate stage.' }
    $StageRoot = Resolve-FullPath $StageRoot
    $expectedStage = Resolve-FullPath (Join-Path ([IO.Path]::GetDirectoryName($ControlLauncherPath)) 'candidate')
    if (![String]::Equals($StageRoot, $expectedStage, [StringComparison]::OrdinalIgnoreCase)) { throw 'Native verification does not identify the owning installer candidate stage.' }
    $sourceAncestors += [SoAILauncher.NativeFilesystemHandles]::RetainDirectoryAncestors($StageRoot)
}
$backupMarker = Join-Path $resolvedBackupRoot '.soai-upgrade-backup'
$backupMarkerValue = 'SoAI upgrade backup V1'

if ($Mode -eq 'Backup') {
    if (Test-Path -LiteralPath $resolvedBackupRoot) {
        if (Get-ChildItem -LiteralPath $resolvedBackupRoot -Force | Select-Object -First 1) {
            throw 'The SoAI upgrade backup directory is not empty.'
        }
    }
    else {
        New-Item -ItemType Directory -Path $resolvedBackupRoot | Out-Null
    }
    try {
        $manifestPath = Join-Path $resolvedInstallRoot 'installer-support\installed-files.txt'
        if (!(Test-Path -LiteralPath $manifestPath -PathType Leaf)) {
            throw 'The existing SoAI installation manifest is missing.'
        }
        foreach ($relative in (@($runtimeRollbackPaths) + @(Get-ManifestRollbackRoots -ManifestPath $manifestPath) | Sort-Object -Unique)) {
            Copy-RollbackPath -SourceRoot $resolvedInstallRoot -DestinationRoot $resolvedBackupRoot -RelativePath $relative
        }
        foreach ($relative in $installationMetadataPaths) {
            $source = Resolve-ChildPath -Root $resolvedInstallRoot -Child $relative
            if (Test-Path -LiteralPath $source -PathType Leaf) {
                $destination = Resolve-ChildPath -Root $resolvedBackupRoot -Child $relative
                Copy-RollbackPath -SourceRoot $resolvedInstallRoot -DestinationRoot $resolvedBackupRoot -RelativePath $relative
            }
        }
        Set-Content -LiteralPath $backupMarker -Value $backupMarkerValue -Encoding ASCII
    }
    catch {
        $backupError = $_
        try {
            Remove-Item -LiteralPath (ConvertTo-ExtendedPath $resolvedBackupRoot) -Recurse -Force -ErrorAction Stop
        }
        catch {
            Write-Warning 'Failed to remove the incomplete SoAI upgrade backup.'
        }
        throw $backupError
    }
    exit 0
}

if (!(Test-Path -LiteralPath $backupMarker -PathType Leaf)) {
    throw 'The SoAI upgrade backup marker is missing.'
}

if ([IO.File]::ReadAllText($backupMarker).TrimEnd([char[]]"`r`n") -cne $backupMarkerValue) {
    throw 'The SoAI upgrade backup marker is invalid; preserve the backup for repair.'
}

if ($Mode -eq 'Restore') {
    $committed = @(Get-ChildItem -LiteralPath $resolvedInstallRoot -Force | Where-Object { $_.Name.StartsWith('.soai_update_cleanup_', [StringComparison]::Ordinal) -or ($_.Name.StartsWith('.soai_update_transaction_', [StringComparison]::Ordinal) -and (Test-Path -LiteralPath (Join-Path $_.FullName 'success_complete') -PathType Leaf)) })
    if ($committed.Count -gt 0) {
        Restore-PluginUpgradeState -Root $resolvedInstallRoot -Phase cleanup
        Write-Host 'Terminal transaction cleanup completed. Native application restoration was not performed; the retained backup remains available for state verification.'
        exit 3
    }
    Restore-PluginUpgradeState -Root $resolvedInstallRoot -Phase restore
    $backupManifest = Resolve-ChildPath -Root $resolvedBackupRoot -Child 'installer-support\installed-files.txt'
    if (!(Test-Path -LiteralPath $backupManifest -PathType Leaf)) {
        throw 'The retained SoAI installation manifest is missing; no restoration was attempted.'
    }
    foreach ($line in Get-Content -LiteralPath $backupManifest) {
        $relative = $line.Trim()
        if ($relative.Length -gt 0) {
            Resolve-ChildPath -Root $resolvedBackupRoot -Child $relative | Out-Null
        }
    }
    if (![string]::IsNullOrWhiteSpace($CandidateManifestPath)) {
        & (Join-Path $PSScriptRoot 'Remove-SoAI.ps1') -InstallRoot $resolvedInstallRoot -Mode Upgrade -ManifestPath $CandidateManifestPath -ControlLauncherPath $ControlLauncherPath -InstallerRollback
        if (!$?) {
            throw 'The candidate files could not be removed; retained originals were not copied.'
        }
    }
    foreach ($relative in $runtimeRollbackPaths) {
        Remove-RollbackPath -Root $resolvedInstallRoot -RelativePath $relative
    }
    foreach ($item in Get-ChildItem -LiteralPath $resolvedBackupRoot -Force) {
        if ($item.Name -eq '.soai-upgrade-backup' -or $item.Name -eq 'soai.exe') {
            continue
        }
        Copy-RollbackPath -SourceRoot $resolvedBackupRoot -DestinationRoot $resolvedInstallRoot -RelativePath $item.Name
    }
    Restore-Launcher -SourceRoot $resolvedBackupRoot -DestinationRoot $resolvedInstallRoot
    Restore-PluginUpgradeState -Root $resolvedInstallRoot -Phase cleanup
    exit 0
}

if ($Mode -eq 'Prepare') {
    if ([string]::IsNullOrWhiteSpace($StageRoot)) { throw 'Upgrade preparation requires the staged candidate application.' }
    $python = Join-Path $resolvedInstallRoot 'soai_main_venv\Scripts\python.exe'
    $priorPythonPath = $env:PYTHONPATH
    $priorBytecode = $env:PYTHONDONTWRITEBYTECODE
    try {
        $env:PYTHONPATH = Join-Path $StageRoot 'backend'
        $env:PYTHONDONTWRITEBYTECODE = '1'
        $code = @'
import sys
from app.updater.software_update.recovery_bootstrap import resolve_update_recovery_package_paths
sys.path.extend(resolve_update_recovery_package_paths(sys.argv[1]))
from app.updater.installation_plugin_upgrade import prepare_installation_plugin_upgrade
prepare_installation_plugin_upgrade(base_path=sys.argv[1], source=sys.argv[3], staged=sys.argv[3], edition='soai-core', native_backup_root=sys.argv[2])
'@
        Invoke-UpgradeRecoveryCommand -Root $resolvedInstallRoot -Python $python -Code $code -Arguments @($resolvedInstallRoot, $resolvedBackupRoot, $StageRoot) -Phase preparation
    }
    finally {
        $env:PYTHONPATH = $priorPythonPath
        $env:PYTHONDONTWRITEBYTECODE = $priorBytecode
    }
    exit 0
}

Remove-Item -LiteralPath (ConvertTo-ExtendedPath $resolvedBackupRoot) -Recurse -Force
}
finally {
    foreach ($ancestor in $backupAncestors) { $ancestor.Dispose() }
    foreach ($ancestor in $sourceAncestors) { $ancestor.Dispose() }
    $coordinator.Dispose()
}
