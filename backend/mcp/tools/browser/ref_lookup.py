from core.mcp.argument_validation import require_non_empty_string_value
from mcp.tools.browser.frame_tree import (
    build_frame_tree_signature,
    resolve_frame_by_path,
)
from mcp.tools.browser.session_access import clear_snapshot_refs
from mcp.tools.browser.snapshot_refs import normalize_ref_alias
from mcp.tools.browser.types import SnapshotRefMapping
from mcp.tools.error import MCPToolError, build_invalid_params_error, get_arg

